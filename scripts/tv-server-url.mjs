// Writes apps/tv/src/server-url.ts before each TV build.
// SERVER_URL wins (e.g. the CloudFront URL); otherwise the Mac's LAN address on port 8080,
// which the Vega Virtual Device can reach (spike S1).
import {writeFileSync} from 'node:fs';
import {networkInterfaces} from 'node:os';

function lanIp() {
  for (const addrs of Object.values(networkInterfaces()))
    for (const a of addrs ?? []) if (a.family === 'IPv4' && !a.internal) return a.address;
  return 'localhost';
}

const url = (process.env.SERVER_URL ?? `http://${lanIp()}:8080`).replace(/\/$/, '');
writeFileSync(
  new URL('../apps/tv/src/server-url.ts', import.meta.url),
  `// Generated by scripts/tv-server-url.mjs. Do not edit.\nexport const SERVER_URL = '${url}';\n`,
);
console.log(`TV app will use ${url}`);
